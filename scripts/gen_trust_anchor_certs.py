"""Generate the certificates behind the trust anchor IDs Chrome advertises.

Chrome's root store marks some intermediates as TLS trust anchors and gives
them trust anchor IDs (draft-ietf-tls-trust-anchor-ids). A client that sends
those IDs tells servers it holds the certificates, and servers such as Google
then omit them from the chain they send over QUIC. curl verifies with a CA
bundle of roots, so the chrome152 target loads these intermediates when it
advertises their IDs (native/patches/curl/0006-trust-anchor-certificates.patch).

usage: gen_trust_anchor_certs.py root_store.textproto additional.certs > out.h

Both files are in Chromium's net/data/ssl/chrome_root_store/.
"""

from __future__ import annotations

import base64
import hashlib
import re
import sys
from pathlib import Path

ENTRY = re.compile(r"^(trust_anchors|additional_certs) \{\n(.*?)^\}", re.M | re.S)
PEM = re.compile(r"-----BEGIN CERTIFICATE-----\n(.*?)-----END CERTIFICATE-----", re.S)


def entries(textproto: str) -> list[tuple[str, str, str]]:
    """(trust anchor ID, sha256, comment) of the intermediates with an ID."""
    out = []
    for m in ENTRY.finditer(textproto):
        kind, body = m.group(1), m.group(2)
        tai = re.search(r'trust_anchor_id: "[^"]*"\s*#\s*([0-9.]+)', body)
        if kind != "additional_certs" or not tai:
            continue
        if not re.search(r"tls_trust_anchor: true", body):
            continue
        sha = re.search(r'sha256_hex: "([0-9a-f]{64})"', body).group(1)
        before = textproto[: m.start()].rstrip().splitlines()[-1]
        out.append((tai.group(1), sha, before.lstrip("# ").strip('"')))
    return out


def pems(certs: str) -> dict[str, str]:
    out = {}
    for m in PEM.finditer(certs):
        der = base64.b64decode("".join(m.group(1).split()))
        out[hashlib.sha256(der).hexdigest()] = m.group(0)
    return out


def main() -> None:
    textproto = Path(sys.argv[1]).read_text()
    by_hash = pems(Path(sys.argv[2]).read_text())
    print("/* Generated by scripts/gen_trust_anchor_certs.py from Chromium's")
    print(" * net/data/ssl/chrome_root_store. Do not edit. */")
    print("struct ossl_trust_anchor_cert {")
    print("  const char *id;")
    print("  const char *pem;")
    print("};")
    print()
    print("static const struct ossl_trust_anchor_cert ossl_trust_anchor_certs[] = {")
    for tai, sha, comment in entries(textproto):
        pem = by_hash[sha]
        print(f"  /* {comment} */")
        print(f'  {{ "{tai}",')
        lines = pem.splitlines()
        for i, line in enumerate(lines):
            end = " }," if i == len(lines) - 1 else ""
            print(f'    "{line}\\n"{end}')
    print("};")


if __name__ == "__main__":
    main()
